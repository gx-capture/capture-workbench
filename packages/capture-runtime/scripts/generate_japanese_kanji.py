"""Write capture_runtime/japanese_kanji/__init__.py, the old-to-Japanese kanji form table.

Usage: generate_japanese_kanji.py <JPShinjitaiCharacters.txt> <Unihan_OtherMappings.txt>

TEA-ASR learned Taiwan Mandarin, so its Japanese transcripts keep many kanji in their old
(Traditional) forms: 會議 for 会議, 天氣 for 天気. Both inputs are checked against the digest of
their upstream bytes:
- OpenCC's JPShinjitaiCharacters.txt (Apache License 2.0) lists each Japanese form with its old
  forms;
- Unihan's kJoyoKanji field lists the jōyō kanji, including their four accepted alternates.
A pair is kept only when its Japanese form is a jōyō kanji and its old form is not, so the table
never rewrites a character standard Japanese writes, and one pass converts fully.
"""

from __future__ import annotations

import hashlib
import sys
from collections import defaultdict
from pathlib import Path

OPENCC_COMMIT = "fae2a0a911c30764e669a7d8b0591cd8e852934a"
OPENCC_SOURCE = (
    f"https://github.com/BYVoid/OpenCC/blob/{OPENCC_COMMIT}"
    "/data/dictionary/JPShinjitaiCharacters.txt"
)
OPENCC_SHA256 = "12cec7250b873ef52b36d8f92218d4f92c0aaf5d8cd7c58fe42d9785bdcdc43a"
UNIHAN_SOURCE = "https://www.unicode.org/Public/18.0.0/ucd/Unihan.zip"
UNIHAN_SHA256 = "fc7bbb8f923fa1e922a4d421aa15387d1c68250cc5e7619bdf81f575ab38472b"
TARGET = (
    Path(__file__).resolve().parents[1]
    / "src"
    / "capture_runtime"
    / "japanese_kanji"
    / "__init__.py"
)
PAIRS_PER_LINE = 16


def _checked(path: Path, sha256: str) -> str:
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != sha256:
        raise SystemExit(f"{path} does not match its upstream digest {sha256}.")
    return data.decode("utf-8")


def _joyo(unihan: str) -> set[str]:
    joyo = set()
    for line in unihan.splitlines():
        if "\tkJoyoKanji\t" in line:
            joyo.add(chr(int(line.split("\t", 1)[0].removeprefix("U+"), 16)))
    return joyo


def pairs(opencc: str, unihan: str) -> list[tuple[str, str]]:
    joyo = _joyo(unihan)
    forms: dict[str, set[str]] = defaultdict(set)
    for line in opencc.splitlines():
        if not line or line.startswith("#"):
            continue
        japanese, olds = line.split("\t", 1)
        for old in olds.split():
            if japanese in joyo and old not in joyo:
                forms[old].add(japanese)
    ambiguous = {old: sorted(japanese) for old, japanese in forms.items() if len(japanese) > 1}
    if ambiguous:
        raise SystemExit(f"Old forms with more than one jōyō form: {ambiguous}")
    return sorted((old, next(iter(japanese))) for old, japanese in forms.items())


def module(table: list[tuple[str, str]]) -> str:
    rows = [
        " ".join(old + japanese for old, japanese in table[start : start + PAIRS_PER_LINE])
        for start in range(0, len(table), PAIRS_PER_LINE)
    ]
    lines = "\n".join(f'    "{row} "' for row in rows)
    return f'''"""Japanese standard forms of old (Traditional) kanji, for Japanese transcripts.

Generated by scripts/generate_japanese_kanji.py; do not edit. The pairs come from OpenCC's
JPShinjitaiCharacters.txt, licensed under the Apache License 2.0 (see LICENSE in this directory):
{OPENCC_SOURCE}
Only pairs whose Japanese form is a jōyō kanji and whose old form is not are kept, by the
kJoyoKanji field of Unihan_OtherMappings.txt in Unicode 18.0.0:
{UNIHAN_SOURCE}
"""

# Each pair is an old form followed by its Japanese form.
PAIRS = (
{lines}
)
TABLE = str.maketrans({{pair[0]: pair[1] for pair in PAIRS.split()}})
'''


def main() -> None:
    opencc = _checked(Path(sys.argv[1]), OPENCC_SHA256)
    unihan = _checked(Path(sys.argv[2]), UNIHAN_SHA256)
    table = pairs(opencc, unihan)
    TARGET.write_bytes(module(table).encode("utf-8"))
    print(f"wrote {len(table)} pairs to {TARGET}")


if __name__ == "__main__":
    main()
