from __future__ import annotations

import argparse
from pathlib import Path

from capture_runtime.release import (
    capture_document_schema_release_sha256,
    write_capture_document_schema,
)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--typescript-output", type=Path)
    arguments = parser.parse_args()
    write_capture_document_schema(arguments.output)
    if arguments.typescript_output is not None:
        arguments.typescript_output.parent.mkdir(parents=True, exist_ok=True)
        digest = capture_document_schema_release_sha256()
        arguments.typescript_output.write_bytes(
            (
                "// Generated by capture-runtime/scripts/generate_schema.py. Do not edit.\n"
                "import schema from './capture-document-v1.schema.json';\n\n"
                "export const GENERATED_CAPTURE_DOCUMENT_V1_JSON_SCHEMA = schema;\n"
                "export const GENERATED_CAPTURE_DOCUMENT_V1_SCHEMA_SHA256 =\n"
                f"  '{digest}' as const;\n"
            ).encode()
        )


if __name__ == "__main__":
    main()
